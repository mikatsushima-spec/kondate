export function findArt(name:string){
 const key=normalized(kana(name));
 const exact=foodCatalog.find(x=>normalized(kana(x.name))===key);
 if(exact)return exact.art;
 const equivalent=equivalentArt[key];
 if(equivalent)return foodCatalog.find(x=>normalized(kana(x.name))===normalized(kana(equivalent)))?.art;
 return key==="やさいじる"?2:undefined;
}
